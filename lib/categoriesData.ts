export function getCategoriasFiltradas(loja: string): CategoriaDesempenho[] {
  if (loja === 'Todas as Lojas') {
    return CATEGORIAS_MERCADO_LIVRE;
  }
  const cleanLoja = loja.replace('Loja ', '').trim();
  return CATEGORIAS_MERCADO_LIVRE.filter(c => c.lojaId === cleanLoja);
}

export function getProdutosFiltrados(loja: string, categoriaId?: string, subcategoriaId?: string): ProdutoCategoriaDetalhe[] {
  let list = PRODUTOS_CATEGORIAS;
  if (loja !== 'Todas as Lojas') {
    const cleanLoja = loja.replace('Loja ', '').trim();
    list = list.filter(p => p.lojaId === cleanLoja);
  }
  if (categoriaId && categoriaId !== 'todas') {
    list = list.filter(p => p.categoriaId === categoriaId);
  }
  if (subcategoriaId && subcategoriaId !== 'todas') {
    const cat = CATEGORIAS_MERCADO_LIVRE.find(c => c.subcategoriaId === subcategoriaId);
    if (cat) {
      list = list.filter(p => p.subcategoriaNome === cat.subcategoriaNome);
    }
  }
  return list;
}
